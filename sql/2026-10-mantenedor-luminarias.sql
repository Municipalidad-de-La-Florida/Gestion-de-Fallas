-- Contrato y mantenedor de cada falla, según quién atiende la luminaria (Luminaria.gpkg) o el circuito (Circuitos.gpkg, CONTRATO_MANT).
-- Cada falla nueva queda con dos datos: CONTRATO (Elecnor / Enel X - Clever: quién cobra) y MANTENEDOR (SINEC / CLEVER: quién atiende).
-- Reemplaza la regla "Masivo -> un contrato / normal -> otro": Masivo deja de decidir el contrato.
--
--  * Falla en un punto: se mira el N.° de llave del punto y las luminarias que tiene (puede tener una vial y una peatonal
--    con distinto mantenedor). Si la falla es vial (F01, F04, F05) o peatonal (F29, F32, F33) se usa el mantenedor de las
--    luminarias de ese uso; si no hay de ese uso, o la falla no es ni vial ni peatonal, se miran todas las del punto.
--    Si resulta un solo contrato, es ese. Si hay dos distintos, o el mantenedor es "SIN MANTENIMIENTO" / "EN RECEPCION" /
--    desconocido, la falla queda SIN CONTRATO (pendiente de revisar). Si el contrato es uno solo pero el punto tiene
--    luminarias de SINEC y de CLEVER a la vez, la falla queda con contrato y SIN MANTENEDOR (lo elige el admin o ITO).
--  * Falla de circuito: el contrato y el mantenedor del circuito (columna circuitos.mantenedor).
--  * Los puntos en cascada de un circuito heredan contrato y mantenedor de la falla del circuito.
--
-- No modifica las fallas ya creadas (para eso, ver 2026-10-mantenedor-recalcular-*.sql). Re-ejecutable.
-- Ejecutar ANTES de correr actualizar_capas_v3.py.

-- ============ 1. Equivalencia: texto de la capa -> contrato y mantenedor ============
-- Se puede editar a mano (update ... set contrato_id = ...) sin tocar código. contrato_id vacío = sin contrato (pendiente).
create table if not exists public.mantenedores_equivalencia (
  texto text primary key,                -- tal como viene en la capa, en MAYÚSCULAS y sin espacios sobrantes
  contrato_id uuid references public.contratos(id) on delete set null,
  mantenedor text,                       -- quién atiende: 'SINEC' o 'CLEVER' (vacío = sin mantenedor)
  nota text
);
alter table public.mantenedores_equivalencia add column if not exists mantenedor text;

insert into public.mantenedores_equivalencia (texto, contrato_id, mantenedor, nota)
select v.texto, (select c.id from public.contratos c where lower(btrim(c.nombre)) = v.contrato), v.mantenedor, v.nota
from (values
  ('ELECNOR SINEC',     'elecnor',         'SINEC',  'Lo atiende SINEC bajo el contrato de Elecnor (incluye lo municipal)'),
  ('ELECNOR CLEVER',    'elecnor',         'CLEVER', 'Lo atiende CLEVER bajo el contrato de Elecnor'),
  ('ENEL X SINEC',      'enel x - clever', 'SINEC',  'Lo atiende SINEC bajo el contrato de Enel X - Clever'),
  ('SIN MANTENIMIENTO', null,              null,     'Sin contrato: queda pendiente de revisar'),
  ('EN RECEPCION',      null,              null,     'Sin contrato: queda pendiente de revisar')
) as v(texto, contrato, mantenedor, nota)
on conflict (texto) do nothing;

-- ============ 2. Luminarias por llave (se recarga completa con actualizar_capas_v3.py) ============
create table if not exists public.luminarias_mantenimiento (
  id bigint generated by default as identity primary key,
  llave integer not null,
  id_inventario integer,
  uso text,                              -- USO_LUM tal como viene en la capa
  uso_grupo text,                        -- 'VIAL', 'PEATONAL' u 'OTRO' (ornamental, plaza, paradero, cancha, vacío)
  mantenimiento text,                    -- MANTENIMIENTO tal como viene en la capa
  propiedad text
);
create index if not exists luminarias_mantenimiento_llave_idx on public.luminarias_mantenimiento (llave);

-- ============ 3. Mantenedor de cada circuito y de cada falla ============
alter table public.circuitos add column if not exists mantenedor text;   -- texto de la capa (CONTRATO_MANT)
alter table public.fallas add column if not exists mantenedor text;      -- 'SINEC' / 'CLEVER'

-- ============ 4. Seguridad: solo el admin ve las tablas de apoyo; los triggers leen con security definer ============
alter table public.mantenedores_equivalencia enable row level security;
alter table public.luminarias_mantenimiento enable row level security;
drop policy if exists admin_todo on public.mantenedores_equivalencia;
create policy admin_todo on public.mantenedores_equivalencia for all to authenticated
  using (public.mi_rol() = 'admin') with check (public.mi_rol() = 'admin');
drop policy if exists admin_todo on public.luminarias_mantenimiento;
create policy admin_todo on public.luminarias_mantenimiento for all to authenticated
  using (public.mi_rol() = 'admin') with check (public.mi_rol() = 'admin');

-- ============ 5. Funciones que resuelven contrato y mantenedor ============
-- Uso de la luminaria según el código de falla de un punto (null = no distingue: se miran todas las luminarias del punto).
create or replace function public.uso_de_codigo(p_codigo text)
returns text language sql immutable set search_path to 'public'
as $function$
  select case when p_codigo in ('F01', 'F04', 'F05') then 'VIAL'
              when p_codigo in ('F29', 'F32', 'F33') then 'PEATONAL'
              else null end;
$function$;

-- Contrato y mantenedor de un punto lumínico (por gid) para un uso dado. Sin filas = no se puede determinar con certeza.
create or replace function public.asignacion_de_punto(p_gid integer, p_uso text default null)
returns table (r_contrato uuid, r_mantenedor text)
language plpgsql stable security definer set search_path to 'public'
as $function$
declare
  v_llave integer;
  v_todos boolean;
  v_contratos uuid[];
  v_mants text[];
  v_sin_contrato boolean;
  v_sin_mant boolean;
begin
  select p.llave into v_llave from public.puntos_luminarios p where p.gid = p_gid;
  if v_llave is null then return; end if;

  v_todos := p_uso is null
             or not exists (select 1 from public.luminarias_mantenimiento l0 where l0.llave = v_llave and l0.uso_grupo = p_uso);

  select array_agg(distinct e.contrato_id) filter (where e.contrato_id is not null),
         array_agg(distinct e.mantenedor) filter (where e.mantenedor is not null),
         coalesce(bool_or(e.contrato_id is null), false),
         coalesce(bool_or(e.mantenedor is null), false)
    into v_contratos, v_mants, v_sin_contrato, v_sin_mant
    from public.luminarias_mantenimiento l
    left join public.mantenedores_equivalencia e on e.texto = upper(btrim(l.mantenimiento))
   where l.llave = v_llave and (v_todos or l.uso_grupo = p_uso);

  if v_contratos is null or array_length(v_contratos, 1) <> 1 or v_sin_contrato then return; end if;
  r_contrato := v_contratos[1];
  r_mantenedor := null;
  if v_mants is not null and array_length(v_mants, 1) = 1 and not v_sin_mant then
    r_mantenedor := v_mants[1];
  end if;
  return next;
end;
$function$;

-- Contrato y mantenedor de un circuito (por gid) según su mantenedor; sin filas si no tiene o no está en la equivalencia.
create or replace function public.asignacion_de_circuito(p_gid integer)
returns table (r_contrato uuid, r_mantenedor text)
language sql stable security definer set search_path to 'public'
as $function$
  select e.contrato_id, e.mantenedor
    from public.circuitos c
    join public.mantenedores_equivalencia e on e.texto = upper(btrim(c.mantenedor))
   where c.gid = p_gid and e.contrato_id is not null;
$function$;

-- ============ 6. Falla nueva: contrato y mantenedor salen de la capa (ya no del Masivo) ============
-- Los puntos en cascada no entran aquí: heredan de su circuito (trg_heredar_contrato_cascada).
create or replace function public.contrato_por_defecto_insert()
returns trigger language plpgsql set search_path to 'public'
as $function$
declare
  v_contrato uuid;
  v_mant text;
begin
  if new.contrato_id is null and not coalesce(new.cascada, false) then
    if new.tipo = 'punto' and new.ref_punto_gid is not null then
      select a.r_contrato, a.r_mantenedor into v_contrato, v_mant
        from public.asignacion_de_punto(new.ref_punto_gid, public.uso_de_codigo(new.tipo_falla)) a;
    elsif new.tipo = 'linea' and new.ref_circuito_gid is not null then
      select a.r_contrato, a.r_mantenedor into v_contrato, v_mant
        from public.asignacion_de_circuito(new.ref_circuito_gid) a;
    end if;
    if v_contrato is not null then
      new.contrato_id := v_contrato;
      new.mantenedor := coalesce(new.mantenedor, v_mant);
    end if;
  end if;
  return new;
end;
$function$;

-- Cambiar una falla a Masivo (o quitarle Masivo) ya no le cambia el contrato.
drop trigger if exists trg_z_contrato_por_defecto_upd on public.fallas;

-- Un punto de cascada nace con el contrato y el mantenedor de su circuito...
create or replace function public.heredar_contrato_cascada()
returns trigger language plpgsql set search_path to 'public'
as $function$
declare
  v_contrato uuid;
  v_mant text;
begin
  if new.cascada then
    select f.contrato_id, f.mantenedor into v_contrato, v_mant from public.fallas f where f.id = new.circuito_origen_id;
    if new.contrato_id is null then new.contrato_id := v_contrato; end if;
    if new.mantenedor is null then new.mantenedor := v_mant; end if;
  end if;
  return new;
end;
$function$;

-- ...y los sigue si después cambia el del circuito.
create or replace function public.propagar_contrato_cascada()
returns trigger language plpgsql security definer set search_path to 'public'
as $function$
begin
  if new.tipo = 'linea'
     and (new.contrato_id is distinct from old.contrato_id or new.mantenedor is distinct from old.mantenedor) then
    update public.fallas set contrato_id = new.contrato_id, mantenedor = new.mantenedor where circuito_origen_id = new.id;
  end if;
  return new;
end;
$function$;

-- Quién puede cambiar el contrato o el mantenedor de una falla ya creada: admin, ITO y quienes ingresan fallas
-- (los contratistas, camiones y observadores no).
create or replace function public.proteger_contrato_falla()
returns trigger language plpgsql set search_path to 'public'
as $function$
begin
  if (new.contrato_id is distinct from old.contrato_id or new.mantenedor is distinct from old.mantenedor)
     and public.mi_rol() in ('contratista', 'camion', 'observador') then
    raise exception 'No tienes permiso para cambiar el contrato o el mantenedor de una falla.';
  end if;
  return new;
end;
$function$;
drop trigger if exists trg_proteger_contrato_falla on public.fallas;
create trigger trg_proteger_contrato_falla before update of contrato_id, mantenedor on public.fallas
  for each row execute function public.proteger_contrato_falla();
